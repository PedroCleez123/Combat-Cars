import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const rootIndex = args.indexOf("--root");
const root = rootIndex === -1 ? repositoryRoot : path.resolve(args[rootIndex + 1] || "");
const unknownArgs = args.filter((arg, index) => arg !== "--check" && arg !== "--root" && (rootIndex === -1 || index !== rootIndex + 1));
if (unknownArgs.length || (rootIndex !== -1 && !args[rootIndex + 1])) {
  throw new Error(`Usage: node tools/generate-arena-contract.mjs [--check] [--root <directory>]`);
}

const contract = JSON.parse(await readFile(path.join(root, "data/combat-alpha-geometry.json"), "utf8"));
validateContract(contract);
const artifacts = new Map([
  ["src/generated/combat-alpha-geometry.js", renderJavaScript(contract)],
  ["tools/shared/combat_alpha_geometry.generated.hpp", renderCppHeader(contract)],
]);
let stale = false;
for (const [relativePath, expected] of artifacts) {
  const absolutePath = path.join(root, relativePath);
  if (checkOnly) {
    let actual;
    try {
      actual = await readFile(absolutePath, "utf8");
    } catch {
      actual = null;
    }
    if (actual !== expected) {
      console.error(`Generated arena contract is missing or stale: ${relativePath}`);
      stale = true;
    }
  } else {
    await mkdir(path.dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, expected, "utf8");
  }
}
if (stale) process.exitCode = 1;
else console.log(checkOnly ? "Arena contract artifacts are current." : "Generated arena contract artifacts.");

function validateContract(value) {
  if (value?.schemaVersion !== 1 || value?.units !== "UU") throw new Error("Unsupported arena contract schema or units.");
  const { width, depth, height, curveRadius } = value.arena || {};
  if (![width, depth, height, curveRadius].every(Number.isFinite) || width <= 0 || depth <= 0 || height <= 0 || curveRadius <= 0) {
    throw new Error("Arena dimensions and curve radius must be positive finite UU values.");
  }
  if (!Array.isArray(value.obstacles) || value.obstacles.length !== 2) throw new Error("combat-alpha requires the central block and ramp obstacle records.");
  if (!Array.isArray(value.covers) || value.covers.length !== 6) throw new Error("combat-alpha requires exactly six static covers.");
  const obstacleIds = new Map();
  for (const obstacle of value.obstacles) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(obstacle.id || "") || obstacleIds.has(obstacle.id)
      || ![obstacle.x, obstacle.z].every(Number.isFinite)) {
      throw new Error("Central obstacle IDs and positions must be unique and finite.");
    }
    obstacleIds.set(obstacle.id, obstacle);
  }
  const block = obstacleIds.get("central-block");
  const ramp = obstacleIds.get("south-ramp");
  if (obstacleIds.size !== 2 || !block || !ramp
    || block.kind !== "box" || ![block.width, block.depth, block.height].every(value => Number.isFinite(value) && value > 0)
    || ramp.kind !== "closed-convex-wedge" || ![ramp.run, ramp.width, ramp.height].every(value => Number.isFinite(value) && value > 0)) {
    throw new Error("Central obstacle dimensions and kinds are incomplete or invalid.");
  }
  const ids = new Set();
  for (const cover of value.covers) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(cover.id || "") || ids.has(cover.id)) throw new Error(`Cover IDs must be present and unique: ${cover.id || "<empty>"}`);
    ids.add(cover.id);
    if (![cover.x, cover.z, cover.width, cover.depth, cover.height].every(Number.isFinite)
      || cover.width <= 0 || cover.depth <= 0 || cover.height <= 0) {
      throw new Error(`Cover ${cover.id} must have finite position and positive dimensions.`);
    }
    if (cover.role !== "cover" || !["container", "tires"].includes(cover.visualKind) || !cover.symmetryGroup) {
      throw new Error(`Cover ${cover.id} is missing presentation or symmetry metadata.`);
    }
  }
  if (!ids.has("tire-cover-blue") || !ids.has("tire-cover-red")) throw new Error("Both tire-cover records are required.");
}

function renderJavaScript(value) {
  return `// Generated by tools/generate-arena-contract.mjs from data/combat-alpha-geometry.json. Do not edit.\nconst deepFreeze = value => {\n  if (value && typeof value === "object" && !Object.isFrozen(value)) {\n    Object.freeze(value);\n    Object.values(value).forEach(deepFreeze);\n  }\n  return value;\n};\n\nexport const COMBAT_ALPHA_GEOMETRY = deepFreeze(${JSON.stringify({ arena: value.arena, obstacles: value.obstacles, covers: value.covers }, null, 2)});\n`;
}

function renderCppHeader(value) {
  const cppFloat = number => `${Number.isInteger(number) ? `${number}.0` : number}f`;
  const rows = value.covers.map(cover => `  { "${cover.id}", ${cppFloat(cover.x)}, ${cppFloat(cover.z)}, ${cppFloat(cover.width)}, ${cppFloat(cover.depth)}, ${cppFloat(cover.height)} },`).join("\n");
  const { width, depth, height, curveRadius } = value.arena;
  const block = value.obstacles.find(({ id }) => id === "central-block");
  const ramp = value.obstacles.find(({ id }) => id === "south-ramp");
  return `// Generated by tools/generate-arena-contract.mjs from data/combat-alpha-geometry.json. Do not edit.\n#pragma once\n\nnamespace CombatCarsArenaGeometry {\ninline constexpr float kCombatAlphaWidth = ${cppFloat(width)};\ninline constexpr float kCombatAlphaDepth = ${cppFloat(depth)};\ninline constexpr float kCombatAlphaHeight = ${cppFloat(height)};\ninline constexpr float kCombatAlphaCurveRadius = ${cppFloat(curveRadius)};\ninline constexpr float kCentralBlockX = ${cppFloat(block.x)};\ninline constexpr float kCentralBlockZ = ${cppFloat(block.z)};\ninline constexpr float kCentralBlockWidth = ${cppFloat(block.width)};\ninline constexpr float kCentralBlockDepth = ${cppFloat(block.depth)};\ninline constexpr float kCentralBlockHeight = ${cppFloat(block.height)};\ninline constexpr float kSouthRampX = ${cppFloat(ramp.x)};\ninline constexpr float kSouthRampZ = ${cppFloat(ramp.z)};\ninline constexpr float kSouthRampRun = ${cppFloat(ramp.run)};\ninline constexpr float kSouthRampWidth = ${cppFloat(ramp.width)};\ninline constexpr float kSouthRampHeight = ${cppFloat(ramp.height)};\n\nstruct CoverSpec {\n  const char* id;\n  float x;\n  float z;\n  float width;\n  float depth;\n  float height;\n};\n\ninline constexpr CoverSpec kCombatAlphaCovers[] = {\n${rows}\n};\n} // namespace CombatCarsArenaGeometry\n`;
}
